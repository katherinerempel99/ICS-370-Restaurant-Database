(2, 'Manager'),
(3, 'Owner');

-- create Login tables 
CREATE table Users ( 
    userID varchar(8) NOT NULL, 
    password varchar(20) NOT NULL, 
    -- hash is generated by computer
    authLevel integer NOT NULL DEFAULT 1,
    firstName varchar(30),
    lastName varchar(30),
    storeID varchar(8),
    Primary key(userID),
    Foreign key (storeID) references Store(storeID),
    Foreign key (authLevel) references user_rank(id)
);

-- create Recipe
CREATE table Recipe (
    recipeID varchar(8) NOT NULL,
    recipeName varchar(64),
    Primary key (recipeID)
);

CREATE table MenuCategory (
    id integer primary key, -- no identity, so you can control the values
    category varchar(20) NOT NULL unique
);

