-- create Store table
CREATE table Store (
    storeID varchar(8) NOT NULL,
    address varchar(100),
    hours varchar(64),
    phone integer,
    storeEmail varchar(50),
    Primary key(storeID)
);

-- create fake enumerators for Users
CREATE table user_rank (
    id integer primary key, -- no identity, so you can control the values
    rank varchar(20) NOT NULL unique
);

INSERT INTO user_rank (id, rank) VALUES
