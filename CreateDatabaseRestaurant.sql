-- create Menu tables 
CREATE table Menu (
    menuID varchar(8) NOT NULL,
    category integer not null,
    servingSize varchar(64),
    Primary key (menuID),
    Foreign key (category) references MenuCategory(id)
);

-- create MenuDescription
CREATE table MenuDescription (
    menuID varchar(8) NOT NULL,
    recipeID varchar (8) NOT NULL,
    menuName varchar(64),
    menuPrice decimal(10,2),
    allergyInfo varchar(64),
    Foreign key (menuID) references Menu(menuID),
    Foreign key (recipeID) references Recipe(recipeID)
);

-- create Inventory tables 
CREATE table Item (
    itemID varchar(8) NOT NULL,
    itemName varchar(64) NOT NULL,
    allergyInfo varchar(64),
    Primary key(itemID)
);

CREATE table Inventory (
    itemID varchar(8) NOT NULL,
    storeID varchar(8) NOT NULL,
    quantity numeric(8,2) CHECK (quantity >= 0),
    --Primary key (itemID),
    Foreign key (itemID) references Item(itemID),
    Foreign key (storeID) references Store(storeID)
);

-- create Event tables
/* added e in front to avoid datatype look alike */

CREATE table Event (
    eventID varchar(8) NOT NULL,
    eventName varchar(64) NOT NULL,
    eDate date,
    eTime time, 
    category varchar(64),
    storeID varchar(8),
    PRIMARY KEY(eventID),
    FOREIGN KEY (storeID) REFERENCES Store(storeID)
);

CREATE table EventDescription (
    eventID varchar(8) NOT NULL,
    eDescription TEXT,
    eventName varchar(64) NOT NULL,
    eLocation varchar(64),
    FOREIGN KEY (eventID) REFERENCES Event(eventID)
);

-- create Inquiry
CREATE table Inquiry(
    inquiryID varchar(8) NOT NULL,
    iTime time,
    iDate date,
    storeID varchar(8) NOT NULL,
    PRIMARY KEY(inquiryID),
    FOREIGN KEY (storeID) REFERENCES Store(storeID)
);

CREATE table InquiryDescription(
    inquiryID varchar(8) NOT NULL,
    phoneNumber int NOT NULL,
    firstName varchar(30) NOT NULL,
    lastName varchar(30) NOT NULL,
    IEmail varchar(50) NOT NULL,
    iDescription TEXT,
    FOREIGN KEY (inquiryID) REFERENCES Inquiry(inquiryID)
);


-- weak entity sets
CREATE table StoreStaff(
    userID varchar(8) NOT NULL,
    storeID varchar(8) NOT NULL,
    Foreign KEY(userID) REFERENCES Users(userID),
    Foreign Key(storeID) REFERENCES Store(storeID)
);

CREATE table EventItems (
    eventID varchar(8) NOT NULL,
    itemID varchar(8) NOT NULL,
    quantityNeeded int,
    FOREIGN KEY (eventID) REFERENCES Event(eventID),
    FOREIGN KEY (itemID) REFERENCES Item(itemID)
);

-- create MenuItem
CREATE table MenuItem (
    menuID varchar(8) NOT NULL,
    itemID varchar(8) NOT NULL,
    Foreign key (menuID) references Menu(menuID),
    FOREIGN KEY (itemID) REFERENCES Item(itemID)
);



-- create RecipeIngredients for linking ingredients (Items) to recipes
CREATE table RecipeIngredients (
    recipeID varchar(8) NOT NULL,
    itemID varchar(8) NOT NULL,
    Foreign key (recipeID) references Recipe(recipeID),
    Foreign Key (itemID) REFERENCES Item(itemID)
);

-- create InquiryEvent table for linking customer submitted inquiries to staff created events
CREATE table InquiryEvents (
    eventID varchar(8),
    inquiryID varchar(8),
    FOREIGN KEY (eventID) REFERENCES Event(eventID),
    FOREIGN KEY (inquiryID) REFERENCES Inquiry(inquiryID)
);